function compileMac(omp_inc, omp_lib)
if nargin < 2 || isempty(omp_inc) || isempty(omp_lib)
    if exist('findOpenMPMacOs', 'file') ~= 2
        this_dir = fileparts(mfilename('fullpath'));
        curr = this_dir;
        while ~isempty(curr) && ~isfile(fullfile(curr, 'compileAll.m'))
            parent = fileparts(curr);
            if strcmp(parent, curr), break; end
            curr = parent;
        end
        if isfile(fullfile(curr, 'compileAll.m'))
            addpath(fullfile(curr, 'sources', 'utils'));
        end
    end
    [omp_inc, omp_lib] = findOpenMPMacOs();
end

% Determine host macOS deployment target
[status, ver_str] = system('sw_vers -productVersion');
if status == 0
    mac_ver = strtrim(ver_str);
else
    mac_ver = '15.0';
end
ver_flag = ['-mmacosx-version-min=' mac_ver];

% Compile command for NSY_rFSAI_compute
mex('-silent', ...
    '-O', ...
    '-R2018a',...
    omp_inc, ...
    '-lmwblas', ...
    '-lmwlapack', ...
    ['CXXFLAGS="$CXXFLAGS -std=c++14 -O3 -Xpreprocessor -fopenmp -fPIC ' ver_flag '"'], ...
    ['LDFLAGS="$LDFLAGS ' ver_flag ' -O3"'], ...
    'NSY_rFSAI_compute.cpp', ...
    'Compute_nsy_rfsai.cpp', ...
    'KapGrad_NSY.cpp', ...
    'SymmetrizePattern.cpp', ...
    'compress_nsy_fsai.cpp', ...
    'cpt_nsy_rfsai.cpp', ...
    'extract_diag.cpp', ...
    'gather_fullsys.cpp', ...
    'heapsort.cpp', ...
    'merge_row_patt.cpp', ...
    'ri_sortsplit_nsy.cpp', ...
    'transpose.cpp', ...
    'DEBUG.cpp', ...
    'wrCSRmat.cpp', ...
    omp_lib);
end
