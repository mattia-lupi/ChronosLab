function compileWin(win_cfg)
if nargin < 1 || isempty(win_cfg)
    if exist('findCompilerWindows', 'file') ~= 2
        this_dir = fileparts(mfilename('fullpath'));
        curr = this_dir;
        while ~isempty(curr) && ~isfile(fullfile(curr, 'compileAll.m'))
            parent = fileparts(curr);
            if strcmp(parent, curr), break; end
            curr = parent;
        end
        if isfile(fullfile(curr, 'compileAll.m'))
            addpath(fullfile(curr, 'sources', 'utils'));
        end
    end
    win_cfg = findCompilerWindows();
end

if strcmp(win_cfg.compiler, 'mingw')
    cflags = sprintf('CXXFLAGS="$CXXFLAGS %s %s"', win_cfg.cxx14_flags, win_cfg.omp_cflags);
    lflags = sprintf('LDFLAGS="$LDFLAGS %s"', win_cfg.omp_lflags);
else
    cflags = sprintf('COMPFLAGS="$COMPFLAGS %s"', win_cfg.omp_cflags);
    lflags = sprintf('LINKFLAGS="$LINKFLAGS %s"', win_cfg.omp_lflags);
end

mex('-O', ...
    '-R2018a', ...
    win_cfg.blas_lib, ...
    win_cfg.lapack_lib, ...
    cflags, ...
    lflags, ...
    'NSY_rFSAI_compute.cpp', ...
    'Compute_nsy_rfsai.cpp', ...
    'KapGrad_NSY.cpp', ...
    'SymmetrizePattern.cpp', ...
    'compress_nsy_fsai.cpp', ...
    'cpt_nsy_rfsai.cpp', ...
    'extract_diag.cpp', ...
    'gather_fullsys.cpp', ...
    'heapsort.cpp', ...
    'merge_row_patt.cpp', ...
    'ri_sortsplit_nsy.cpp', ...
    'transpose.cpp', ...
    'DEBUG.cpp', ...
    'wrCSRmat.cpp', ...
    win_cfg.extra_libs{:});
end
